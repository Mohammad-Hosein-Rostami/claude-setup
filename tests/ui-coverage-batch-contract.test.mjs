// Contract test: records written by the real ui-check batch record writer are consumed by the real `ui-coverage check`.
// Covers pass, fail naming, unrun width, that batch state names equal the ids `ui-coverage expand` generates, compare records
// (frame width), a scaffolded states file round-tripping into `check`, helpful messages for unmatched records, and locale matching.
import test from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compareRecords, responsiveRecords, writeBatchResults } from '../home/tools/ui-check/lib/batch-records.mjs';
import { makeTempDir } from './temp-dir-helpers.mjs';

const CLI = fileURLToPath(new URL('../home/tools/ui-coverage/ui-coverage.mjs', import.meta.url));
const run = (...args) => spawnSync(process.execPath, [CLI, ...args], { encoding: 'utf8' });

const WIDTHS = [320, 1024];
const LOCALES = [{ tag: 'en', dir: 'ltr' }, { tag: 'fa', dir: 'rtl' }];
const BUTTON_STATES = run('states').stdout.match(/^button -> (.+)$/m)[1].split(', ');
const MATRIX = {
  locales: LOCALES,
  widths: WIDTHS,
  searched: { backend: ['rg -il mjml api/ -> 0 hits'], siblings: [], reference: ['rg -il validate ../ref -> 0 hits'] },
  deliverable: { reviewUrl: 'http://localhost:4099/review', mockExcluded: 'grep -c authmock dist -> 0' },
  surfaces: [{
    id: 'login', kind: 'screen', source: 'src/login.tsx',
    controls: [{ id: 'submit', class: 'button', component: 'src/Button.tsx', mountedAt: 'src/login.tsx:1', states: BUTTON_STATES, reference: 'none: no design reference exists' }],
  }],
};

async function expandedMatrix() {
  const dir = makeTempDir('ui-batch-contract-');
  const file = join(dir, 'matrix.json');
  await writeFile(file, JSON.stringify(MATRIX));
  await mkdir(join(dir, 'src'));
  await writeFile(join(dir, 'src', 'login.tsx'), "import { Button } from './Button.tsx';\n"); // the mount site check reads this file
  assert.equal(run('expand', file).status, 0);
  const cells = JSON.parse(await readFile(file, 'utf8')).cells;
  return { dir, file, cells };
}

// One batch state per (state id, locale), measured at `widths`; `failing` is a "state|locale|width" key that gets a finding.
async function batchResults(dir, cells, { widths = WIDTHS, failing, localeOf = (tag) => tag } = {}) {
  const ids = [...new Set(cells.map((c) => c.state))];
  const records = [];
  for (const state of ids) {
    for (const { tag } of LOCALES) {
      const md = join(dir, `report-${state.replace(':', '_')}-${tag}.md`);
      await writeFile(md, '# report');
      const findings = widths
        .filter((width) => failing === `${state}|${tag}|${width}`)
        .map((width) => ({ width, check: 'overflow', element: 'button#submit', detail: 'clipped text' }));
      records.push(...responsiveRecords({ surface: 'login', state, locale: localeOf(tag) }, widths, { md, findings }));
    }
  }
  return writeBatchResults(dir, records).results;
}

test('records from the real batch writer for every expanded cell pass ui-coverage check (exit 0)', async () => {
  const { dir, file, cells } = await expandedMatrix();
  const results = await batchResults(dir, cells);
  const out = run('check', file, '--results', results);
  assert.equal(out.status, 0, out.stdout);
  assert.match(out.stdout, /result: PASS/);
});

test('a failing batch record exits 1 and the message names surface, state, locale and width', async () => {
  const { dir, file, cells } = await expandedMatrix();
  const results = await batchResults(dir, cells, { failing: 'submit:hover|fa|320' });
  const out = run('check', file, '--results', results);
  assert.equal(out.status, 1);
  assert.match(out.stdout, /\[fail\] fail: login submit:hover fa @320/);
});

test('records for only one width leave the other width unrun and exit 1', async () => {
  const { dir, file, cells } = await expandedMatrix();
  const results = await batchResults(dir, cells, { widths: [320] });
  const out = run('check', file, '--results', results);
  assert.equal(out.status, 1);
  assert.match(out.stdout, /@1024/);
  assert.match(out.stdout, /result: FAIL/);
});

test('state names a batch run uses for the resting state and a control state match the ids expand generates', async () => {
  const { dir, file, cells } = await expandedMatrix();
  // The names a batch states.json author writes, per the ui-check README: no matching cell would be an unmatched-result.
  const batchNames = ['rest', 'submit:hover'];
  const generated = new Set(cells.map((c) => c.state));
  for (const name of batchNames) assert.ok(generated.has(name), `${name} is not generated by expand`);
  const md = join(dir, 'r.md');
  await writeFile(md, '# report');
  const records = batchNames.flatMap((state) => responsiveRecords({ surface: 'login', state, locale: 'en' }, WIDTHS, { md, findings: [] }));
  const results = writeBatchResults(dir, records).results;
  assert.doesNotMatch(run('check', file, '--results', results).stdout, /unmatched-result/);
});

const FRAME_WIDTH = 1024;
const COMPARE_RESULT = { md: '', pixels: { pass: true }, elementRows: [] };

test('compare records from the real writer fill the cell at the Figma frame width (an integer), so a Figma state can pass', async () => {
  const { dir, file, cells } = await expandedMatrix();
  const md = join(dir, 'compare.md');
  await writeFile(md, '# report');
  const ids = [...new Set(cells.map((c) => c.state))];
  const compare = ids.flatMap((state) => LOCALES.flatMap(({ tag }) => compareRecords({ surface: 'login', state, locale: tag }, { ...COMPARE_RESULT, md }, { root: 'body', maxDiff: 0, width: FRAME_WIDTH })));
  const responsive = ids.flatMap((state) => LOCALES.flatMap(({ tag }) => responsiveRecords({ surface: 'login', state, locale: tag }, [320], { md, findings: [] })));
  const results = writeBatchResults(dir, [...compare, ...responsive]).results;
  const out = run('check', file, '--results', results);
  assert.equal(out.status, 0, out.stdout);
  assert.doesNotMatch(out.stdout, /unmatched-result/);
});

test('a scaffolded states file has names the matrix accepts: its keys round-trip through the record writer into check (exit 0)', async () => {
  const { dir, file } = await expandedMatrix();
  const statesFile = join(dir, 'states.json');
  const scaffold = run('scaffold', file, '--out', statesFile);
  assert.equal(scaffold.status, 0, scaffold.stderr);
  const { states } = JSON.parse(await readFile(statesFile, 'utf8'));
  assert.ok(states.length > 0);
  const md = join(dir, 'r.md');
  await writeFile(md, '# report');
  const records = states.flatMap((entry) => responsiveRecords(entry, entry.widths, { md, findings: [] }));
  const results = writeBatchResults(dir, records).results;
  const out = run('check', file, '--results', results);
  assert.equal(out.status, 0, out.stdout);
  assert.match(out.stdout, /result: PASS/);
});

const unmatchedFor = async (overrides) => {
  const { dir, file } = await expandedMatrix();
  const md = join(dir, 'r.md');
  await writeFile(md, '# report');
  const records = responsiveRecords({ surface: 'login', state: 'rest', locale: 'en', ...overrides }, [320], { md, findings: [] });
  const out = run('check', file, '--results', writeBatchResults(dir, records).results);
  return { out, lines: out.stdout.split('\n').filter((line) => line.includes('unmatched-result')) };
};

test('a record with the state name "default" is an error that says to use rest or <control>:<state> and where to list them', async () => {
  const { out, lines } = await unmatchedFor({ state: 'default' });
  assert.equal(out.status, 1);
  assert.equal(lines.length, 1);
  assert.match(lines[0], /unknown state "default": use rest or <control>:<state>; run `ui-coverage states`/);
});

test('a record width outside the matrix widths is an error that says to add the design frame width to widths', async () => {
  const widthRecord = await (async () => {
    const { dir, file } = await expandedMatrix();
    const md = join(dir, 'r.md');
    await writeFile(md, '# report');
    const records = compareRecords({ surface: 'login', state: 'rest', locale: 'en' }, { ...COMPARE_RESULT, md }, { root: 'body', maxDiff: 0, width: 1440 });
    return run('check', file, '--results', writeBatchResults(dir, records).results);
  })();
  assert.equal(widthRecord.status, 1);
  assert.match(widthRecord.stdout, /add the design frame width 1440 to widths/);
});

test('locale tags match case-insensitively: FA fills the fa cells, with no unmatched record', async () => {
  const { dir, file, cells } = await expandedMatrix();
  const results = await batchResults(dir, cells, { localeOf: (tag) => (tag === 'fa' ? 'FA' : tag) });
  const out = run('check', file, '--results', results);
  assert.equal(out.status, 0, out.stdout);
});

test('locale tags match exactly: fa-IR does not fill fa, and the message says so and what to do', async () => {
  const { out, lines } = await unmatchedFor({ locale: 'fa-IR' });
  assert.equal(out.status, 1);
  assert.equal(lines.length, 1);
  assert.match(lines[0], /locale "fa-IR" does not match "fa": tags match exactly/);
  assert.match(lines[0], /use "fa" in the record, or add "fa-IR" to locales/);
});
